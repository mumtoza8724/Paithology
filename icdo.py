COMPILED = [
    (
        [re.compile(p) for p in required],
        [re.compile(p) for p in excluded],
        code,
        title,
    )
    for required, excluded, code, title in RULES
]


def normalize(text):

    text = (text or "").lower().replace("ё", "е")

    # Степень злокачественности (G1–G3) на код не влияет
    text = re.sub(r"\bg\s*-?\s*[1-4x]\b", " ", text)

    return re.sub(r"\s+", " ", text).strip()


def lookup(text):

    """Возвращает (код, название правила) или ("", "")."""

    value = normalize(text)

    if not value:
        return "", ""

    for required, excluded, code, title in COMPILED:
        if all(p.search(value) for p in required) and not any(p.search(value) for p in excluded):
            return code, title

    return "", ""
